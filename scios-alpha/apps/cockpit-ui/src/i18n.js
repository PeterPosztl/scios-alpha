export function normalizeLocale(code) {
  if (SCI_LOCALES.indexOf(code) >= 0) return code;
  return "en-US";
}

export function t(locale, key) {
  const loc = normalizeLocale(locale);
  const pack = SCI_I18N[loc] || SCI_I18N["en-US"];
  if (pack[key] != null) return pack[key];
  if (SCI_I18N["en-US"][key] != null) return SCI_I18N["en-US"][key];
  return key;
}

export function applyChromeI18n(locale) {
  const loc = normalizeLocale(locale);
  document.documentElement.lang = loc.slice(0, 2);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key) el.textContent = t(loc, key);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(loc, key));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key) el.setAttribute("aria-label", t(loc, key));
  });
}

