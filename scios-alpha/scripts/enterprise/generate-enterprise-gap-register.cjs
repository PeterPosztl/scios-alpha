/** @typedef {"PROVEN"|"PARTIAL"|"PROFILE_DISABLED"|"DISCONNECTED"|"ABSENT"|"UNKNOWN"|"DEFERRED"} Status */
/** @typedef {"P0"|"P1"|"P2"|"P3"|null} Priority */

/**
 * @param {object} c
 * @returns {object}
 */
function control(c) {
  const status = c.status;
  const isGap = status !== "PROVEN";
  const severity =
    c.severity ||
    (c.firstReleaseRequired && status === "ABSENT"
      ? "P0"
      : c.firstReleaseRequired && (status === "PARTIAL" || status === "UNKNOWN")
        ? "P1"
        : c.productionRequired
          ? "P2"
          : "P3");
  return {
    controlId: c.id,
    familyId: c.family,
    title: c.title,
    status,
    whyItMatters: c.why,
    currentEvidence: c.evidence || [],
    affectedComponents: c.components || [],
    severity: isGap ? severity : null,
    firstReleaseRequired: !!c.firstReleaseRequired,
    productionRequired: !!c.productionRequired,
    implementationProposal: isGap
      ? c.proposal || "Classify only — do not auto-implement; schedule by severity."
      : null,
    dependencies: c.deps || [],
    acceptanceTest: isGap
      ? c.test ||
        `Prove ${c.id} with fresh diagnostics artifact; no evidence ⇒ UNKNOWN.`
      : `Retained PROVEN only while evidence under diagnostics-export remains current.`,
    isGap,
  };
}

