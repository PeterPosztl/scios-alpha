import assert from "node:assert/strict";
import { test } from "node:test";
import { BLUEPRINT_HOOKS } from "./index.js";
import { buildDigitalActivationWave } from "./digital-activation.js";
import { KG_EDGE_MAP, OS_BLUEPRINT_HOOKS } from "./os-blueprint-integration.js";

test("digital activation REFUSES nationalGraph, LDA PASS, 191 seeds, and 200/200 roles", () => {
  const wave = buildDigitalActivationWave();
  assert.equal(wave.ready, false);
  assert.equal(wave.digitalRuntime, false);
  assert.equal(wave.nationalGraph, false);
  assert.equal(wave.causalQuery, false);
  assert.equal(wave.ldaPass, false);
  assert.equal(wave.lda, "REFUSED");
  assert.equal(wave.seedsComplete, 0);
  assert.equal(wave.seedsResearchRequired, 191);
  assert.equal(wave.roles200Stabilized, false);
  assert.equal(wave.wave, "REFUSED");
  assert.equal(wave.health.fail, 0);
  assert.equal(wave.health.seedsMarkedReady, 0);
  assert.equal(wave.kg.find((c) => c.id === "KG.nationalGraph")?.result, "REFUSED");
  assert.equal(wave.kg.find((c) => c.id === "KG.causalQuery")?.result, "REFUSED");
  assert.equal(wave.kg.find((c) => c.id === "KG.nodeContract")?.result, "ANALOG_CONTRACT");
  assert.equal(wave.ldaChecks.find((c) => c.id === "AgentSystem.LDA.enable")?.result, "REFUSED");
  assert.equal(wave.domains.find((c) => c.id === "Domain.cyber")?.result, "ANALOG_CONTRACT");
  assert.equal(wave.domains.find((c) => c.id === "Domain.hospitality")?.result, "SKIPPED_RESEARCH_REQUIRED");
  assert.equal(wave.domains.find((c) => c.id === "Domain.supply_chain")?.result, "ANALOG_CONTRACT");
  assert.equal(wave.seeds.find((c) => c.id === "Seed.cyber_event")?.result, "ANALOG_CONTRACT");
  assert.equal(wave.seeds.find((c) => c.id === "Seed.hosp_demand")?.result, "SKIPPED_RESEARCH_REQUIRED");
  assert.equal(wave.roles.find((c) => c.id === "RoleCatalog.200")?.result, "REFUSED");
  assert.equal(wave.rolesFullySpecified, 9);
  assert.equal(BLUEPRINT_HOOKS.surfaces.lda.enabled, false);
  assert.equal(BLUEPRINT_HOOKS.surfaces.knowledgeGraph.nationalGraph, false);
  assert.equal(OS_BLUEPRINT_HOOKS.nationalGraph, false);
  assert.equal(KG_EDGE_MAP.belongs_to, "SUPPORTS");
  assert.equal(KG_EDGE_MAP.triggers, "PRODUCES");
  assert.ok(wave.seeds.every((s) => s.result !== "FAIL"));
  assert.ok(!JSON.stringify(wave).includes("\"ldaPass\":true"));
});
